.make_test_rd <- function() {
  rd_text <- "
\\name{my_fun}
\\alias{my_fun}
\\title{A test function}
\\description{Does something test-worthy.}
\\usage{my_fun(x, y = 1)}
\\arguments{
  \\item{x}{A value.}
  \\item{y}{Another value, default \\code{1}.}
}
\\value{Returns \\code{x + y}.}
\\examples{
my_fun(1, 2)
}
\\seealso{\\code{\\link{other_fun}}}
"
  tools::parse_Rd(textConnection(rd_text))
}

test_that(".parse_rd_topic extracts all core fields", {
  rd <- .make_test_rd()
  topic <- .parse_rd_topic(rd, "my_fun.Rd", "testpkg")

  expect_equal(topic$name, "my_fun")
  expect_equal(topic$package, "testpkg")
  expect_equal(topic$aliases, "my_fun")
  expect_equal(topic$title, "A test function")
  expect_equal(topic$description, "Does something test-worthy.")
  expect_match(topic$usage, "my_fun\\(x, y = 1\\)")
  expect_length(topic$arguments, 2)
  expect_equal(topic$arguments[[1]]$name, "x")
  expect_equal(topic$arguments[[1]]$description, "A value.")
  expect_match(topic$value, "x \\+ y")
  expect_match(topic$examples, "my_fun\\(1, 2\\)")
})

test_that(".parse_rd_topic defaults is_private to FALSE when exported_names is unknown", {
  rd <- .make_test_rd()
  topic <- .parse_rd_topic(rd, "my_fun.Rd", "testpkg")

  expect_false(topic$is_private)
})

test_that(".parse_rd_topic flags a documented-but-not-exported function as private", {
  rd <- .make_test_rd()
  topic <- .parse_rd_topic(rd, "my_fun.Rd", "testpkg", exported_names = c("other_fun"))

  expect_true(topic$is_private)
})

test_that(".parse_rd_topic does not flag an exported function as private", {
  rd <- .make_test_rd()
  topic <- .parse_rd_topic(rd, "my_fun.Rd", "testpkg", exported_names = c("my_fun", "other_fun"))

  expect_false(topic$is_private)
})

test_that(".compute_is_private never flags a bare-usage topic (dataset) as private", {
  # dplyr::starwars regression: datasets aren't in NAMESPACE's export()
  # list the way functions are, but that doesn't make them "private" -
  # only topics with at least one callable name are eligible at all.
  expect_false(.compute_is_private("starwars", "starwars", "starwars", character(0)))
})

test_that(".compute_is_private treats NULL exported_names as \"unknown\" (never private)", {
  expect_false(.compute_is_private("secret_helper", "secret_helper", "secret_helper(x)", NULL))
})

test_that(".compute_is_private flags an internal infix operator as private", {
  # Real pkgmd regression: %||% is an unexported helper, but its usage
  # ("x %||% y") never matches the "name(" call-syntax check, so it was
  # silently exempted from private-flagging the same way a dataset is.
  is_private <- .compute_is_private("%||%", "%||%", "x %||% y", exported_names = c("build_reference"))
  expect_true(is_private)
})

test_that(".compute_is_private is FALSE if any callable alias is exported", {
  # e.g. mutate.Rd documents both the generic mutate() (exported) and the
  # S3 method mutate.data.frame() (never separately exported) - the topic
  # as a whole is public because the generic is.
  is_private <- .compute_is_private(
    "mutate",
    c("mutate", "mutate.data.frame"),
    "mutate(.data, ...)\n\nmutate.data.frame(.data, ...)",
    exported_names = "mutate"
  )
  expect_false(is_private)
})

