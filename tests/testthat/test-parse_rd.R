test_that(".parse_rd_arguments collapses multi-line item descriptions to a single line", {
  # Reproduces a real dplyr::pull() rendering bug: Rd source hard-wraps
  # \item{}{} descriptions across lines for readability; left as raw
  # newlines, that breaks the Markdown arguments table (a table cell can't
  # contain a literal newline).
  rd_text <- "
\\name{pull}
\\alias{pull}
\\title{Extract a single column}
\\description{Extracts a column.}
\\arguments{
  \\item{.data}{A data frame, data frame extension (e.g. a tibble), or a
lazy data frame (e.g. from dbplyr or dtplyr). See Methods, below, for
more details.}
  \\item{var}{A variable.}
}
"
  rd <- tools::parse_Rd(textConnection(rd_text))
  topic <- .parse_rd_topic(rd, "pull.Rd", "dplyr")

  expect_length(topic$arguments, 2)
  expect_false(grepl("\n", topic$arguments[[1]]$description, fixed = TRUE))
  expect_equal(
    topic$arguments[[1]]$description,
    "A data frame, data frame extension (e.g. a tibble), or a lazy data frame (e.g. from dbplyr or dtplyr). See Methods, below, for more details."
  )
})

test_that("a multi-line argument description does not break the rendered Markdown table", {
  rd_text <- "
\\name{pull}
\\alias{pull}
\\title{Extract a single column}
\\description{Extracts a column.}
\\arguments{
  \\item{.data}{A data frame, data frame extension (e.g. a tibble), or a
lazy data frame (e.g. from dbplyr or dtplyr). See Methods, below, for
more details.}
  \\item{var}{A variable.}
}
"
  rd <- tools::parse_Rd(textConnection(rd_text))
  topic <- .parse_rd_topic(rd, "pull.Rd", "dplyr")
  md <- .render_topic_md(topic, version = "1.0.0")
  lines <- strsplit(md, "\n")[[1]]

  table_lines <- lines[grepl("^\\|", lines)]
  # Every table row must itself be a complete "| ... | ... |" row - i.e.
  # nothing after the arguments header/separator escaped the table.
  expect_true(all(grepl("^\\|.*\\|$", table_lines)))
  expect_true(any(grepl("`var`", table_lines)))
})

