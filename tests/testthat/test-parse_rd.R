test_that(".parse_rd_arguments skips a malformed \\item with fewer than 2 children instead of erroring", {
  # A well-formed \item{name}{description} always has 2 children; this
  # constructs a malformed one directly (bypassing tools::parse_Rd(), which
  # wouldn't produce such a node from valid Rd source) to verify the parser
  # degrades gracefully instead of crashing with "subscript out of bounds".
  malformed_item <- structure(list("just a name, no description"), Rd_tag = "\\item")
  well_formed_item <- structure(list("y", "A description."), Rd_tag = "\\item")
  arguments_block <- structure(list(malformed_item, well_formed_item), Rd_tag = "\\arguments")
  rd <- list(arguments_block)

  expect_no_error(result <- .parse_rd_arguments(rd))
  expect_length(result, 1)
  expect_equal(result[[1]]$name, "y")
})

