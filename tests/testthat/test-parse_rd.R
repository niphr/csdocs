.write_fixture_description <- function(pkg_dir, name = "fixturepkg") {
  writeLines(
    c(
      glue::glue("Package: {name}"),
      "Title: Fixture Package",
      "Version: 0.0.1",
      "License: MIT"
    ),
    fs::path(pkg_dir, "DESCRIPTION")
  )
}

test_that(".read_rd_db_source reads man/*.Rd directly when present", {
  pkg_dir <- withr::local_tempdir()
  .write_fixture_description(pkg_dir)
  fs::dir_create(fs::path(pkg_dir, "man"))

  writeLines(
    "\\name{foo}\n\\alias{foo}\n\\title{Foo}\n\\description{Does foo.}\n",
    fs::path(pkg_dir, "man", "foo.Rd")
  )
  writeLines(
    "\\name{bar}\n\\alias{bar}\n\\title{Bar}\n\\description{Does bar.}\n",
    fs::path(pkg_dir, "man", "bar.Rd")
  )

  db <- .read_rd_db_source(pkg_dir)

  expect_setequal(names(db), c("foo.Rd", "bar.Rd"))
  expect_s3_class(db[["foo.Rd"]], "Rd")

  topic <- .parse_rd_topic(db[["foo.Rd"]], "foo.Rd", "fixturepkg")
  expect_equal(topic$name, "foo")
  expect_equal(topic$title, "Foo")
})

test_that(".read_rd_db_source falls back to roxygen2 when man/ is missing", {
  skip_if_not_installed("roxygen2")

  pkg_dir <- withr::local_tempdir()
  .write_fixture_description(pkg_dir)
  fs::dir_create(fs::path(pkg_dir, "R"))

  writeLines(
    c(
      "#' Add two numbers",
      "#'",
      "#' @param x A number.",
      "#' @param y A number.",
      "#' @return The sum.",
      "#' @export",
      "add_two <- function(x, y) x + y"
    ),
    fs::path(pkg_dir, "R", "add_two.R")
  )

  db <- .read_rd_db_source(pkg_dir)

  expect_true("add_two.Rd" %in% names(db))
  expect_s3_class(db[["add_two.Rd"]], "Rd")

  topic <- .parse_rd_topic(db[["add_two.Rd"]], "add_two.Rd", "fixturepkg")
  expect_equal(topic$name, "add_two")
  expect_match(topic$usage, "add_two\\(x, y\\)")
  expect_length(topic$arguments, 2)
})

