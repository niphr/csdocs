test_that(".render_arguments_section escapes a literal pipe in a description", {
  # .make_test_topic(arguments = ...) would go through modifyList(), which
  # merges list-valued fields recursively rather than replacing them - set
  # the field directly instead so the override actually takes effect.
  topic <- .make_test_topic()
  topic$arguments <- list(
    list(name = "x", description = "TRUE or FALSE, but written as TRUE|FALSE.")
  )
  section <- .render_arguments_section(topic)
  table_lines <- strsplit(section, "\n")[[1]]
  table_lines <- table_lines[grepl("^\\|", table_lines)]

  expect_true(all(grepl("^\\|.*\\|$", table_lines)))
  expect_match(section, "TRUE\\\\\\|FALSE", fixed = FALSE)
})

test_that(".render_usage_section widens the fence when usage contains embedded backticks", {
  topic <- .make_test_topic(usage = "my_fun(x) # returns ```escaped``` text")
  section <- .render_usage_section(topic)

  expect_match(section, "^## Usage\n\n````r\n", perl = TRUE)
  expect_match(section, "\n````\n\n$")
})

test_that(".render_examples_section widens the fence when examples contain embedded backticks", {
  topic <- .make_test_topic(examples = "# ```r\nmy_fun(1, 2)\n# ```")
  section <- .render_examples_section(topic)

  expect_match(section, "````r\n", fixed = TRUE)
})

test_that("new block sections render with the expected headings and are omitted when empty", {
  topic <- .make_test_topic(
    sections = list(list(title = "Extra info", body = "Some body text.")),
    format = "- **x**: a column",
    note = "A note.",
    source = "https://example.com",
    references = "Some reference.",
    author = "Jane Doe"
  )
  md <- .render_topic_md(topic, version = "1.0.0")

  expect_match(md, "## Extra info\n\nSome body text\\.")
  expect_match(md, "## Format\n\n- \\*\\*x\\*\\*: a column")
  expect_match(md, "## Note\n\nA note\\.")
  expect_match(md, "## Source\n\nhttps://example\\.com")
  expect_match(md, "## References\n\nSome reference\\.")
  expect_match(md, "## Author\n\nJane Doe")

  bare_topic <- .make_test_topic()
  bare_md <- .render_topic_md(bare_topic, version = "1.0.0")
  expect_no_match(bare_md, "## Format")
  expect_no_match(bare_md, "## Note")
  expect_no_match(bare_md, "## Source")
  expect_no_match(bare_md, "## References")
  expect_no_match(bare_md, "## Author")
})

