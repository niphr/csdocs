test_that(".render_index_md surfaces non-heading aliases in an Aliases column", {
  # An S3-method-style alias (my_fun.default) isn't itself callable-looking
  # in the usage block and isn't the heading name - it should still show up
  # somewhere in the index so it stays findable by name.
  topics <- list(.make_test_topic(aliases = c("my_fun", "my_fun.default")))
  index <- .render_index_md(topics, package = "testpkg", version = "1.0.0")

  expect_match(index, "`my_fun\\.default`")
})

