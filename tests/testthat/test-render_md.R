test_that(".render_topic_md renders a non-callable topic without parentheses", {
  # A dataset topic: \usage{} is just a bare name, no call syntax - e.g.
  # dplyr::starwars. Forcing "starwars()" onto it would be misleading.
  topic <- .make_test_topic(name = "starwars", aliases = "starwars", usage = "starwars")
  md <- .render_topic_md(topic, version = "1.0.0")

  expect_match(md, "^# `starwars` — ", perl = TRUE)
  expect_no_match(md, "starwars\\(\\)")
})

test_that(".render_topic_md renders every callable name when a topic documents more than one", {
  # Real dplyr regression: lead-lag.Rd documents both lead() and lag(),
  # under the topic name "lead-lag" (which itself is not callable).
  topic <- .make_test_topic(
    name = "lead-lag",
    aliases = c("lead-lag", "lag", "lead"),
    usage = "lag(x, n = 1L)\n\nlead(x, n = 1L)"
  )
  md <- .render_topic_md(topic, version = "1.0.0")

  expect_match(md, "^# `lag\\(\\)` · `lead\\(\\)` — ", perl = TRUE)
})

