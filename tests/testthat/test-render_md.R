test_that("empty sections are omitted from the full render", {
  topic <- .make_test_topic(value = "", examples = "", seealso = "")

  expect_equal(.render_value_section(topic), "")
  expect_equal(.render_examples_section(topic), "")
  expect_equal(.render_seealso_section(topic), "")

  md <- .render_topic_md(topic, version = "1.0.0")
  expect_no_match(md, "## Details")
  expect_no_match(md, "## Value")
  expect_no_match(md, "## Examples")
  expect_no_match(md, "## See Also")
})

test_that(".render_details_section renders block-level Markdown as-is", {
