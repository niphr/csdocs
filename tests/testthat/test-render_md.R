.make_test_topic <- function(...) {
  defaults <- list(
    name        = "my_fun",
    package     = "testpkg",
    aliases     = "my_fun",
    title       = "A test function",
    description = "Does something test-worthy.",
    usage       = "my_fun(x, y = 1)",
    arguments   = list(
      list(name = "x", description = "A value."),
      list(name = "y", description = "Another value.")
    ),
    details     = "",
    value       = "Returns x + y.",
    examples    = "my_fun(1, 2)",
    seealso     = "[`other_fun()`](other_fun.md)"
  )
  modifyList(defaults, list(...))
}

test_that(".render_topic_md contains title, version and description", {
  topic <- .make_test_topic()
  md <- .render_topic_md(topic, version = "1.0.0")

  expect_match(md, "# `my_fun\\(\\)` — A test function")
  expect_match(md, "\\*\\*Package:\\*\\* testpkg · \\*\\*Version:\\*\\* 1.0.0")
  expect_match(md, "Does something test-worthy.")
})

test_that("sections are separated by a blank line (glue .trim pitfall)", {
  topic <- .make_test_topic()
  md <- .render_topic_md(topic, version = "1.0.0")
  lines <- strsplit(md, "\n")[[1]]

  usage_fence_close <- which(lines == "```")[1]
  expect_equal(lines[usage_fence_close + 1], "")
  expect_equal(lines[usage_fence_close + 2], "## Arguments")
})

test_that(".render_usage_section renders a fenced code block", {
  topic <- .make_test_topic()
  section <- .render_usage_section(topic)

  expect_match(section, "## Usage")
  expect_match(section, "```r\nmy_fun\\(x, y = 1\\)\n```")
})

test_that(".render_usage_section is empty without usage", {
  topic <- .make_test_topic(usage = "")
  expect_equal(.render_usage_section(topic), "")
})

test_that(".render_arguments_section renders a Markdown table", {
  topic <- .make_test_topic()
